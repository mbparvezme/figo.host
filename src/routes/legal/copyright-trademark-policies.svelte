    <ol class="mb-8">
      <li>If the Complaining Party would like to submit a copyright claim for material on which you hold a bona fide copyright, Figo Host requests that the Complaining Party substantiate such claim by providing the following information via email to <a href="mailto:legal@figo.host">legal@figo.host</a>. The words "Copyright Claim" should appear in the subject line of the email.
        <p class="my-4">To be considered effective, a notification of a claimed copyright infringement must be provided to Figo Host and must include the following information:</p>
        <ul>
          <li>An electronic signature of the copyright owner, or a person authorized to act on behalf of the owner, of an exclusive copyright that has allegedly been infringed.</li>
          <li>Identification of the copyrighted work claimed to have been infringed, or, if multiple copyrighted works at a single online site are covered by a single notification, a representative list of such works on that site.</li>
          <li>Identification of the material that is claimed to be infringing or to be the subject of infringing activity and that is to be removed or access to which is to be disabled, and information reasonably sufficient to permit Figo Host to locate the material.</li>
          <li>Information reasonably sufficient to permit Figo Host to contact the Complaining Party, such as an address, telephone number, and, if available, an electronic mail address at which the Complaining Party may be contacted.</li>
          <li>A statement that the Complaining Party has a good faith belief that use of the material in the manner complained of is not authorized by the copyright owner, its agent, or the law.</li>
          <li>A statement that the information in the notification is accurate, and under penalty of perjury, that the Complaining Party is the owner, or is authorized to act on behalf of the owner, of an exclusive right that is allegedly infringed.</li>
          <li>For Copyright Claims, upon receipt of appropriate notification from the Complaining Party, pursuant to Section 1 of Copyright Claims above, Figo Host will initiate an investigation and forward the Complaining Party's written notification to the alleged infringer. While Figo Host is investigating the claim, Figo Host, at its sole discretion and without any legal obligation to do so, may notify the alleged infringer it will lock down the domain name(s), redirect the DNS, and/or if it is solely stored on a Figo Host server, temporarily remove or deny access to the allegedly infringing material.</li>
