        </ul>
      </li>
    </ol>
    <h5>C. Counter Notification Policy</h5>
    <ol class="mb-8">
      <li>Counter Notification. If you have received a notice of copyright or trademark infringement that you wish to challenge based on a good faith belief that the material was removed or disabled as a result of mistake or misidentification of the material to be removed or disabled, you may provide Counter Notification by emailing <a href="mailto:legal@figo.host">legal@figo.host</a> and including the following:
        <ul>
          <li>An electronic signature of the alleged infringer.</li>
          <li>Identification of the material that has been removed or to which access has been disabled and the location at which the material appeared before it was removed or access to it was disabled.</li>
          <li>A statement under penalty of perjury that the alleged infringer has a good faith belief that the material was removed or disabled as a result of mistake or misidentification of the material to be removed or disabled.</li>
