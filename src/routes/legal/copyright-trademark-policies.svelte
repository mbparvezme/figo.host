    <h4>{++i}. COPYRIGHT AND TRADEMARK CLAIMS</h4>
    <ul class="mb-8">
      <li>To notify Figo Host that there has been a copyright or trademark violation, please follow the specific instructions in (A) for filing a trademark claim, or (B) filing a copyright complaint.</li>
      <li>If you are responding to a complaint of infringement, you will need to follow our Counter Notification policy in (C).</li>
    </ul>
    <h5>A. Trademark Claims</h5>
    <ol class="mb-8">
      <li>If you (the "Complaining Party") would like to submit a trademark claim for violation of a mark on which you hold a valid, registered trademark or service mark (registered with the appropriate intellectual property organization of your country; state registrations and registrations on the Supplemental Register are not considered valid for these purposes), Figo Host requests that the Complaining Party substantiate such claim by providing the following information via email to <a href="mailto:legal@figo.host">legal@figo.host</a>. The words "Trademark Claim" should appear in the subject line of the email.
        <p class="my-4">To be considered effective, a notification of a claimed trademark violation must include the following information:</p>
        <ul>
          <li>The trademark, service mark, trade dress, name, or other indicia of origin ("mark") that is claimed to be infringed, including registration number.</li>
          <li>The jurisdiction or geographical area to which the mark applies.</li>
          <li>The name, post office address and telephone number of the owner of the mark identified above.</li>
          <li>The goods and/or services covered by or offered under the mark identified above.</li>
          <li>The date of first use of the mark identified above.</li>
          <li>The date of first use in interstate commerce of the mark identified above.</li>
          <li>A description of the manner in which the Complaining Party believes its mark is being infringed upon.</li>
          <li>Sufficient evidence that the owner of the website that is claimed to be infringing is a Figo Host customer.</li>
          <li>The precise location of the infringing mark, including electronic mail address, etc.</li>
          <li>A good faith certification, signed under penalty of perjury, stating:
            <ul>
              <li>The content of the website [identify website] infringes the rights of another party,</li>
              <li>The name of such said party,</li>
              <li>The mark [identify mark] being infringed, and</li>
              <li>That use of the content of the website claimed to be infringing at issue is not defensible.</li>
            </ul>
          </li>
        </ul>
      </li>
      <li>Upon receipt of the appropriate information identified in Section 1 above, for trademark claims, Figo Host will initiate an investigation and forward the Complaining Party’s written notification to the alleged infringer. While Figo Host is investigating the claim, Figo Host, at its sole discretion and without any legal obligation to do so, may temporarily remove the allegedly infringing material, notify the alleged infringer it will lock down the domain name(s), redirect the DNS,and/or if it is solely stored on a Figo Host server, temporarily remove or deny access to the allegedly infringing material.</li>
      <li>If Figo Host concludes that the Complaining Party has raised a legitimate trademark claim, it may, at its sole discretion and without any legal obligation to do so, continue to suspend the alleged infringer's Figo Host account and/or if it is solely stored on a Figo Host server, deny access to the allegedly infringing material. If Figo Host concludes that the Complaining Party has not raised a legitimate claim, Figo Host will restore access to the allegedly infringing material.</li>
